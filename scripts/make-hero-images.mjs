// Pre-sizes the large photos at the top of pages (heroes, and the Things to do stage) into ready-made WebP
// files, like the Photos & Videos page, so the first visitor never waits while the server converts one
// (0.3-1.2s each, during which the hero shows nothing).
//
//   npm run heroes     (run again after adding or replacing a photo in SOURCES)
//
// Writes public/heroes/<name>-<hash>-<width>.webp and lib/content/heroImages.ts, which HeroImage reads.
/* eslint-disable no-console -- a command-line tool: its report is the output */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const PUBLIC = path.resolve(import.meta.dirname, "../public");
const OUT = path.join(PUBLIC, "heroes");
const WIDTHS = [640, 828, 1080, 1440, 1920, 2560];

const dir = (d) => readdirSync(path.join(PUBLIC, d)).filter((f) => /\.jpe?g$/i.test(f)).map((f) => `${d}/${f}`);
const SOURCES = [
  ...dir("images/heroes"),
  ...dir("images/things-to-do"),
  "photos/home-hero-poster.jpg",
  "photos/drone-hero.jpg",
  "photos/residences-villa.jpg",
  "images/resorts/venues/tavaro-lawn.jpg",
  // Event pages (lib/content/events.ts) use these as their heroes.
  "images/wellness/stillness-retreat.jpg",
  "images/wellness/future-retreat.jpg",
  "images/resorts/monsoon-table.jpg",
  "images/mare/rain-rhythm.jpg",
  "images/mare/coffee-house-arch.jpg",
];

const stem = (f) => path.basename(f).split(".")[0];
const dupes = SOURCES.map(stem).filter((s, i, a) => a.indexOf(s) !== i);
if (dupes.length) throw new Error(`Two photos share a name (HeroImage looks them up by name): ${dupes}`);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const manifest = {};
let bytes = 0;
for (const file of SOURCES) {
  const input = readFileSync(path.join(PUBLIC, file));
  const hash = createHash("sha1").update(input).digest("hex").slice(0, 8);
  const { width } = await sharp(input).rotate().metadata();
  // Never upscale: the largest file is the original's own width.
  const widths = [...WIDTHS.filter((w) => w < width), Math.min(width, WIDTHS.at(-1))];
  for (const w of widths) {
    const buf = await sharp(input).rotate().resize({ width: w }).webp({ quality: 78, effort: 6 }).toBuffer();
    writeFileSync(path.join(OUT, `${stem(file)}-${hash}-${w}.webp`), buf);
    bytes += buf.length;
  }
  const blur = await sharp(input).rotate().resize({ width: 16 }).webp({ quality: 50 }).toBuffer();
  manifest[stem(file)] = { h: hash, w: widths, blur: `data:image/webp;base64,${blur.toString("base64")}` };
  console.log(`${file}: ${widths.join(", ")}`);
}

writeFileSync(
  path.resolve(import.meta.dirname, "../lib/content/heroImages.ts"),
  `// Generated by scripts/make-hero-images.mjs (npm run heroes). Do not edit by hand.\n` +
    `export const HERO_IMAGES: Record<string, { h: string; w: number[]; blur: string }> = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(`${SOURCES.length} photos, ${Math.round(bytes / 1024)} KB in public/heroes`);
